import React from 'react';
import ReactDOM from 'react-dom/client';

import store from './store';
import history from './history';
import Root from './components/common/Root';

import './i18n';

// Boot the Pendo agent once with an anonymous visitor. The signed-in user is identified
// in the initializeCore saga. In demo mode the login page reads the email or username
// and password from the URL hash, so the hash is cleared from every URL Pendo records.
// The app uses browser history (no hash routing), so the hash carries no page identity.
window.pendo.initialize({
  visitor: {
    id: '',
  },
  location: {
    transforms: [{ attr: 'hash', action: 'Clear' }],
  },
});

const root = ReactDOM.createRoot(document.getElementById('root'));
root.render(React.createElement(Root, { store, history }));
